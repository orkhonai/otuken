"""Fingerprint an Ubuntu initramfs without extracting or executing its files."""

import gzip
import hashlib
import io
import json
import re
import stat
import subprocess
import tempfile
from collections import defaultdict

LIMIT = 256 * 1024**2
NEWC = (b"070701", b"070702")
MDADM_DATE = re.compile(rb"(?m)^# This configuration was auto-generated on [A-Z][a-z]{2}, "
                       rb"\d{1,2} [A-Z][a-z]{2} \d{4} \d{2}:\d{2}:\d{2} [+-]\d{4} by mkconf$")


def sha(payload):
    return hashlib.sha256(payload).hexdigest()


def archive(data, offset):
    entries = {}
    hardlinks = defaultdict(list)
    while data.startswith(NEWC, offset):
        fields = [int(data[p:p + 8], 16) for p in range(offset + 6, offset + 110, 8)]
        inode, mode, uid, gid, links, _, size, dev_major, dev_minor, r_major, r_minor, name_size, checksum = fields
        start = offset + 110
        name_end = start + name_size
        payload = (name_end + 3) & ~3
        end = payload + size
        if not name_size or end > len(data) or data[name_end - 1] != 0:
            raise ValueError("Malformed initramfs record")
        name = data[start:name_end - 1].removeprefix(b"./")
        crc = data.startswith(b"070702", offset)
        offset = (end + 3) & ~3
        if name == b"TRAILER!!!":
            break
        if not name or name in entries or name.startswith(b"/") or b".." in name.split(b"/"):
            raise ValueError("Unsafe or duplicate initramfs member")
        content = data[payload:end]
        if crc and sum(content) & 0xFFFFFFFF != checksum:
            raise ValueError("Invalid initramfs entry CRC")
        if stat.S_ISREG(mode) and links == 1:
            if name == b".random-seed" and not mode & 0o7111:
                content = b""
            elif name == b"etc/mdadm/mdadm.conf":
                content = MDADM_DATE.sub(b"# This configuration was auto-generated by mkconf", content)
        item = entries[name] = [mode, uid, gid, len(content), sha(content), r_major, r_minor]
        if stat.S_ISREG(mode) and links > 1:
            hardlinks[(dev_major, dev_minor, inode)].append((name, item))
    else:
        raise ValueError("Initramfs archive is missing its trailer")
    for group in hardlinks.values():
        payloads = {(row[3], row[4]) for _, row in group if row[3]}
        if len(payloads) > 1:
            raise ValueError("Inconsistent initramfs hard links")
        members = sorted(name.hex() for name, _ in group)
        for _, row in group:
            if payloads:
                row[3:5] = next(iter(payloads))
            row.append(members)
    return sorted((name.hex(), record) for name, record in entries.items()), offset


def expand(data):
    if data.startswith(b"\x1f\x8b"):
        with gzip.GzipFile(fileobj=io.BytesIO(data)) as stream:
            result = stream.read(LIMIT + 1)
    elif data.startswith(b"\x28\xb5\x2f\xfd"):
        with tempfile.TemporaryFile() as source:
            source.write(data)
            source.seek(0)
            with subprocess.Popen(["/usr/bin/zstd", "-qdc"], stdin=source, stdout=subprocess.PIPE) as process:
                result = process.stdout.read(LIMIT + 1)
                if len(result) > LIMIT:
                    process.kill()
                if process.wait():
                    raise ValueError("Unable to decompress initramfs")
    else:
        raise ValueError("Unsupported initramfs compression")
    if len(result) > LIMIT:
        raise ValueError("Expanded initramfs exceeds its size limit")
    return result


def fingerprint(path):
    with path.open("rb") as stream:
        data = stream.read(LIMIT + 1)
    if len(data) > LIMIT:
        raise ValueError("Initramfs exceeds its size limit")
    archives = []
    offset = 0
    expanded = False
    while offset < len(data):
        if data[offset] == 0:
            offset += 1
        elif data.startswith(NEWC, offset):
            entries, offset = archive(data, offset)
            archives.append(entries)
        elif not expanded:
            data, offset = expand(data[offset:]), 0
            expanded = True
        else:
            raise ValueError("Unsupported data inside initramfs")
    if not archives:
        raise ValueError("Initramfs archive is empty")
    return sha(json.dumps(archives, separators=(",", ":")).encode())
